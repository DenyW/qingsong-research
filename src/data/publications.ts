export const featuredPublications = publications
  .filter((publication) => publication.featuredRank !== undefined)
  .sort((a, b) => (a.featuredRank ?? 99) - (b.featuredRank ?? 99));

export const publicationsByYear = publications.reduce<Record<number, Publication[]>>(
  (groups, publication) => {
    (groups[publication.year] ??= []).push(publication);
    return groups;
  },
  {},
);

export const publicationYears = Object.keys(publicationsByYear)
  .map(Number)
  .sort((a, b) => b - a);
